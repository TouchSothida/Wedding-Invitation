# Convert photos to WebP 640/1280/2000, strip EXIF/GPS, write gallery list.
import glob, json, os
from PIL import Image, ImageOps
src='photos_src'; out='public/img'; os.makedirs(out,exist_ok=True)
items=[]
for i,f in enumerate(sorted(glob.glob(src+'/*.JPG'))):
    im=ImageOps.exif_transpose(Image.open(f)).convert('RGB')
    w,h=im.size; name=f'p{i+1:02d}'
    for t in (640,1280,2000):
        r=im.copy(); r.thumbnail((t,t),Image.LANCZOS)
        r.save(f'{out}/{name}-{t}.webp','WEBP',quality=80,method=6)  # no exif passed => stripped
    items.append({'id':name,'w':w,'h':h})
open('src/data/gallery.js','w').write('// generated by scripts/photos.py\nexport default '+json.dumps(items)+';\n')
print(len(items),'photos')
